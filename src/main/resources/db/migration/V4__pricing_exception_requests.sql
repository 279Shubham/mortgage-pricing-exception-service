CREATE TABLE pricing_exception_request (
    id                     UUID                        PRIMARY KEY,
    application_id         VARCHAR(20)                 NOT NULL REFERENCES mortgage_application (id),
    requested_by           VARCHAR(40)                 NOT NULL REFERENCES app_user (id),
    status                 VARCHAR(20)                 NOT NULL CHECK (status IN ('PENDING', 'APPROVED', 'DECLINED', 'WITHDRAWN')),
    current_revision       INTEGER                     NOT NULL,
    submitted_at           TIMESTAMP(3) WITH TIME ZONE NOT NULL,
    version                BIGINT                      NOT NULL,
    pending_application_id VARCHAR(20) GENERATED ALWAYS AS (CASE WHEN status = 'PENDING' THEN application_id END),
    CONSTRAINT one_pending_request_per_application UNIQUE (pending_application_id)
);

CREATE TABLE request_revision (
    id              UUID                        PRIMARY KEY,
    request_id      UUID                        NOT NULL REFERENCES pricing_exception_request (id),
    revision_number INTEGER                     NOT NULL,
    discount_bps    INTEGER                     NOT NULL CHECK (discount_bps > 0),
    reason          VARCHAR(1000)               NOT NULL,
    created_at      TIMESTAMP(3) WITH TIME ZONE NOT NULL,
    CONSTRAINT one_row_per_revision UNIQUE (request_id, revision_number)
);

CREATE TABLE request_event (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_id      UUID                        NOT NULL REFERENCES pricing_exception_request (id),
    event_type      VARCHAR(30)                 NOT NULL,
    revision_number INTEGER                     NOT NULL,
    actor_id        VARCHAR(40)                 NOT NULL REFERENCES app_user (id),
    occurred_at     TIMESTAMP(3) WITH TIME ZONE NOT NULL
);
